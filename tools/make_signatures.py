"""Generate src/sigs.h (masked byte signatures) from a code image of the game.

The signatures are short runs of the game's own ARM instructions with every position-dependent field masked out
(branch offsets, pc-relative load offsets). The plugin scans the running game's code for them at start-up to find the
functions it needs, so it never relies on fixed addresses.

You need a code image extracted from your OWN copy of Ocarina of Time 3D (the decompressed code loaded at
0x00100000). It is not part of this repository. Point OOT3D_CANONICAL_CODE at it:

    OOT3D_CANONICAL_CODE=/path/to/code.bin python -I tools/make_signatures.py src/sigs.h

The addresses below are where the functions sit in the image this project was developed with; a different game
build needs different addresses (and then the plugin's own scan would refuse that build anyway).

Pure Python (no capstone needed, so it runs under `python -I`); the ARM classifier is cross-checked against
capstone in the tests when it is available.
"""
import os
import struct
import sys
from dataclasses import dataclass

ENV_IMAGE = "OOT3D_CANONICAL_CODE"
BASE = 0x00100000

MSG_CTX_ADDR = 0x005C1878           # expected message-context pointer (checked by the tests)
GETSTATE_LITERAL_INSN = 16          # `ldr r0,[pc,#0x14]` that loads the message context
MSG_CTX_LITERAL_OFFSET = 0x5C       # pool word offset from Message_GetState start

PADHOLD_START, PADHOLD_COUNT, PADHOLD_SITE = 0x4233C0, 18, 0x4233D8


def image_path():
    p = os.environ.get(ENV_IMAGE, "")
    return p if p and os.path.isfile(p) else None


@dataclass(frozen=True)
class Target:
    name: str
    cname: str
    addr: int
    count: int            # leading instructions used
    func_end: int         # lower bound: signature window must end at/below this (before any pool)
    keep_literal_imm: tuple = ()  # instruction indexes whose ldr-literal imm12 stays unmasked


# NOTE: the input-update owner entry is 0x41E968 (0x41E944 is the tail of the previous function's literal pool);
# 0x41E968 has exactly one bl caller and starts with `ldr r2,[pc,#..]; push {r4,r5,lr}`.
TARGETS = (
    Target("InputOwner", "kSigInputOwner", 0x41E968, 24, 0x41EC10),
    # Only 19 instructions exist before the literal pool, and with every
    # pc-relative imm masked the 19-insn window matches 2 places (0x3769D8 and
    # 0x410788).  Leaving the context-literal ldr's imm12 unmasked (it is the
    # very offset kMsgCtxLiteralOffset depends on) makes it unique.
    Target("MessageGetState", "kSigMessageGetState", 0x3769D8, 19, 0x376A24,
           (GETSTATE_LITERAL_INSN,)),
    Target("MessageLoader", "kSigMessageLoader", 0x2CD2B4, 24, 0x2CD5B0),
    Target("StartTextbox", "kSigStartTextbox", 0x367C7C, 24, 0x367CF4),
)


def classify(w):
    """'branch' (b/bl/blx imm), 'literal' (ldr/ldrb/ldrh/... [pc,#imm], add/sub rX,pc,#imm) or None."""
    if (w >> 25) & 7 == 5:
        return "branch"
    if (w & 0x0E100000) == 0x04100000 and (w >> 16) & 15 == 15:   # ldr/ldrb [pc,#+-imm12]
        return "literal"
    if (w & 0x0F4F0090) == 0x014F0090 and (w & 0x60) != 0:        # ldrh/ldrsb/ldrsh/ldrd/strh.. [pc,#imm8], any L
        return "literal_h"
    if (w & 0x0FEF0000) in (0x028F0000, 0x024F0000):              # add/sub rX,pc,#imm
        return "literal"
    return None


def word_mask(w, keep_imm=False):
    k = classify(w)
    if k == "branch":
        return 0xFF000000
    if k == "literal" and not keep_imm:
        return 0xFFFFF000
    if k == "literal_h" and not keep_imm:
        return 0xFFFFF0F0
    return 0xFFFFFFFF


def pc_literal_target(w, addr):
    """Address read by a pc-relative load, or None."""
    k = classify(w)
    if k == "literal" and (w & 0x0E100000) == 0x04100000:
        imm = w & 0xFFF
        return addr + 8 + (imm if (w >> 23) & 1 else -imm)
    return None


def make_signature(image, addr, instructions=24, keep_literal_imm=()):
    o = addr - BASE
    sig, mask = bytearray(), bytearray()
    for i in range(instructions):
        w = struct.unpack_from("<I", image, o + 4 * i)[0]
        sig += struct.pack("<I", w)
        mask += struct.pack("<I", word_mask(w, i in keep_literal_imm))
    return bytes(sig), bytes(mask)


def literal_offset(image, func, insn_index):
    """Offset from `func` of the pool word loaded by the pc-relative ldr at insn_index."""
    a = func + 4 * insn_index
    w = struct.unpack_from("<I", image, a - BASE)[0]
    return pc_literal_target(w, a) - func


def _fmt(bs):
    return ", ".join("0x%02X" % b for b in bs)


def c_header_text(image):
    """The full text of src/sigs.h (LF line endings)."""
    lines = [
        "/* GENERATED by tools/make_signatures.py --emit-c -- do not edit. */",
        "#ifndef SIGS_H",
        "#define SIGS_H",
        "",
    ]
    for t in TARGETS:
        sig, mask = make_signature(image, t.addr, t.count, t.keep_literal_imm)
        lines += [
            "/* %s: %d instructions (%d bytes) from canonical 0x%08X */" % (t.name, t.count, len(sig), t.addr),
            "#define %s_len %d" % (t.cname, len(sig)),
            "static const unsigned char %s_bytes[%d] = {%s};" % (t.cname, len(sig), _fmt(sig)),
            "static const unsigned char %s_mask[%d] = {%s};" % (t.cname, len(sig), _fmt(mask)),
            "",
        ]
    # PadHold: the pad reader's epilogue; the mid-function hook site is `ldr r0,[r5]; bic r0,r0,#0x2000` at +0x18
    sig, mask = make_signature(image, PADHOLD_START, PADHOLD_COUNT)
    lines += [
        "/* PadHold: %d instructions (%d bytes) from canonical 0x%08X; hook site = +0x%X */"
        % (PADHOLD_COUNT, len(sig), PADHOLD_START, PADHOLD_SITE - PADHOLD_START),
        "#define kSigPadHold_len %d" % len(sig),
        "#define kSigPadHold_site 0x%X" % (PADHOLD_SITE - PADHOLD_START),
        "static const unsigned char kSigPadHold_bytes[%d] = {%s};" % (len(sig), _fmt(sig)),
        "static const unsigned char kSigPadHold_mask[%d] = {%s};" % (len(sig), _fmt(mask)),
        "",
    ]
    off = literal_offset(image, 0x3769D8, GETSTATE_LITERAL_INSN)
    assert off == MSG_CTX_LITERAL_OFFSET
    lines += ["#define kMsgCtxLiteralOffset 0x%X" % off, "", "#endif", ""]
    return "\n".join(lines)


def write_c_header(image, path):
    with open(path, "w", newline="\n") as f:
        f.write(c_header_text(image))
    return path


if __name__ == "__main__":
    src = image_path()
    if not src:
        sys.exit("set %s to a code image extracted from your own copy of the game" % ENV_IMAGE)
    out = sys.argv[1] if len(sys.argv) > 1 and sys.argv[1] != "--emit-c" else (
        sys.argv[2] if len(sys.argv) > 2 else None)
    if not out:
        sys.exit("usage: make_signatures.py [--emit-c] OUT.h")
    img = open(src, "rb").read()
    print("wrote", os.path.abspath(write_c_header(img, out)))
